"use client";

import { keepPreviousData } from "@tanstack/react-query";
import { Download } from "lucide-react";
import { useState, type ReactNode } from "react";
import { toast } from "sonner";
import { CHART_COLORS, TrendChart } from "@/components/charts/trend-chart";
import { PageHeader } from "@/components/shared/page-header";
import { PeriodFilter } from "@/components/shared/period-filter";
import { SectionCard } from "@/components/shared/section-card";
import { StatusBadge } from "@/components/shared/status-badge";
import { Button } from "@/components/ui/button";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { $api, downloadFile } from "@/lib/api/client";
import { errorMessage } from "@/lib/api/errors";
import { formatCompactINR, formatINR, formatNumber } from "@/lib/utils/format";
import { bucketLabel, PERIOD_BUCKET, PERIOD_LABELS, type Period } from "@/lib/utils/period";

type Report = "sales" | "points" | "scans-by-status" | "top-retailers" | "top-products" | "scheme-performance";

/** Downloads the report as CSV, generated by the API over every matching row for the period. */
function ExportButton({ report, period, disabled }: { report: Report; period: Period; disabled?: boolean }) {
  const [busy, setBusy] = useState(false);
  return (
    <Button
      variant="outline"
      size="sm"
      disabled={disabled || busy}
      onClick={async () => {
        setBusy(true);
        try {
          await downloadFile(`/api/v1/admin/reports/${report}`, { period, format: "csv", limit: 100 }, `levik-${report}-${period}.csv`);
        } catch (error) {
          toast.error(errorMessage(error));
        } finally {
          setBusy(false);
        }
      }}
    >
      <Download /> CSV
    </Button>
  );
}

function SimpleTable({ headers, rows, empty }: { headers: Array<{ label: string; right?: boolean }>; rows: ReactNode[][]; empty: string }) {
  if (rows.length === 0) return <p className="px-5 py-8 text-center text-sm text-muted-foreground">{empty}</p>;
  return (
    <div className="overflow-x-auto">
      <Table>
        <TableHeader>
          <TableRow className="bg-muted/60">
            {headers.map((h) => (
              <TableHead key={h.label} className={`text-xs uppercase ${h.right ? "text-right" : ""}`}>
                {h.label}
              </TableHead>
            ))}
          </TableRow>
        </TableHeader>
        <TableBody>
          {rows.map((cells, i) => (
            <TableRow key={i}>
              {cells.map((cell, j) => (
                <TableCell key={j} className={headers[j]?.right ? "text-right tabular-nums" : ""}>
                  {cell}
                </TableCell>
              ))}
            </TableRow>
          ))}
        </TableBody>
      </Table>
    </div>
  );
}

export function ReportsView() {
  const [period, setPeriod] = useState<Period>("90d");
  const params = { params: { query: { period } } };
  const listParams = { params: { query: { period, limit: 10 } } };
  const opts = { placeholderData: keepPreviousData };
  const { data: dashboard } = $api.useQuery("get", "/api/v1/admin/dashboard", params, opts);
  const { data: sales = [] } = $api.useQuery("get", "/api/v1/admin/reports/sales", params, opts);
  const { data: points = [] } = $api.useQuery("get", "/api/v1/admin/reports/points", params, opts);
  const { data: statusCounts = [] } = $api.useQuery("get", "/api/v1/admin/reports/scans-by-status", params, opts);
  const { data: retailers = [] } = $api.useQuery("get", "/api/v1/admin/reports/top-retailers", listParams, opts);
  const { data: products = [] } = $api.useQuery("get", "/api/v1/admin/reports/top-products", listParams, opts);
  const { data: schemes = [] } = $api.useQuery("get", "/api/v1/admin/reports/scheme-performance", params, opts);
  const label = PERIOD_LABELS[period];
  const bucket = PERIOD_BUCKET[period];
  const kpis = dashboard?.kpis;
  const salesTrend = sales.map((r) => ({ ...r, label: bucketLabel(r.bucket, bucket) }));
  const pointsTrend = points.map((r) => ({ ...r, label: bucketLabel(r.bucket, bucket) }));
  const totalScans = statusCounts.reduce((sum, x) => sum + x.count, 0) || 1;

  return (
    <div>
      <PageHeader
        title="Reports"
        description="Programme reports calculated by the API. Each CSV export covers the selected period."
        actions={<PeriodFilter value={period} onChange={setPeriod} />}
      />
      <div className="grid gap-6 xl:grid-cols-2">
        <SectionCard
          title="Verified sales by period"
          description={`${label} · ${formatINR(kpis?.verifiedSales ?? 0)} from approved invoices (pre-GST)`}
          actions={<ExportButton report="sales" period={period} />}
        >
          <TrendChart data={salesTrend} xKey="label" series={[{ key: "sales", label: "Verified sales", color: CHART_COLORS.primary }]} valueFormatter={formatCompactINR} ariaLabel="Verified sales by period" />
        </SectionCard>
        <SectionCard
          title="Points issued and redeemed"
          description={`${label} · ${formatNumber(kpis?.pointsIssued ?? 0)} issued · ${formatNumber(kpis?.pointsRedeemed ?? 0)} redeemed (net)`}
          actions={<ExportButton report="points" period={period} />}
        >
          <TrendChart
            data={pointsTrend}
            xKey="label"
            series={[
              { key: "earned", label: "Issued", color: CHART_COLORS.primary },
              { key: "redeemed", label: "Redeemed (net)", color: CHART_COLORS.gold },
            ]}
            ariaLabel="Points issued and redeemed"
          />
        </SectionCard>
        <SectionCard
          title="Scans by status"
          description={label}
          actions={<ExportButton report="scans-by-status" period={period} disabled={statusCounts.length === 0} />}
          bodyClassName="p-0"
        >
          <SimpleTable
            headers={[{ label: "Status" }, { label: "Scans", right: true }, { label: "Share", right: true }]}
            empty="No scans in this period."
            rows={statusCounts.map((s) => [<StatusBadge key="s" status={s.status} />, formatNumber(s.count), `${Math.round((s.count / totalScans) * 100)}%`])}
          />
        </SectionCard>
        <SectionCard
          title="Top-performing retailers"
          description={`${label} · approved invoice value`}
          actions={<ExportButton report="top-retailers" period={period} disabled={retailers.length === 0} />}
          bodyClassName="p-0"
        >
          <SimpleTable
            headers={[{ label: "Retailer" }, { label: "Invoices", right: true }, { label: "Sales", right: true }, { label: "Incentive pts", right: true }]}
            empty="No approved invoices in this period."
            rows={retailers.map((r) => [
              <div key="r">
                <p className="font-medium">{r.name}</p>
                <p className="text-xs text-muted-foreground">{r.city}</p>
              </div>,
              r.invoices,
              formatINR(r.sales),
              formatNumber(r.points),
            ])}
          />
        </SectionCard>
        <SectionCard
          title="Top-scanned products"
          description={label}
          actions={<ExportButton report="top-products" period={period} disabled={products.length === 0} />}
          bodyClassName="p-0"
        >
          <SimpleTable
            headers={[{ label: "Product" }, { label: "Scans", right: true }, { label: "Approved", right: true }, { label: "Points", right: true }]}
            empty="No scans in this period."
            rows={products.map((p) => [
              <div key="p">
                <p className="font-medium">{p.name}</p>
                <p className="text-xs text-muted-foreground">{p.category}</p>
              </div>,
              p.scans,
              p.approved,
              formatNumber(p.points),
            ])}
          />
        </SectionCard>
        <SectionCard
          title="Scheme performance"
          description="All schemes · current progress"
          actions={<ExportButton report="scheme-performance" period={period} disabled={schemes.length === 0} />}
          bodyClassName="p-0"
        >
          <SimpleTable
            headers={[{ label: "Scheme" }, { label: "Status" }, { label: "Participants", right: true }, { label: "Achieved", right: true }, { label: "Avg %", right: true }]}
            empty="No schemes configured."
            rows={schemes.map((s) => [
              <div key="s">
                <p className="font-medium">{s.name}</p>
                <p className="text-xs text-muted-foreground capitalize">{s.role}</p>
              </div>,
              <StatusBadge key="b" status={s.status} />,
              s.participants,
              s.achievers,
              `${s.averagePercent}%`,
            ])}
          />
        </SectionCard>
      </div>
    </div>
  );
}
