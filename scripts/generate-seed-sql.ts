import { createSeedDatabase, DEMO_ADMIN } from "@/lib/mock-data/seed";

const anchor = new Date();
const db = createSeedDatabase(anchor);

type Raw = { raw: string };
type Value = string | number | boolean | null | undefined | Raw;

const raw = (sql: string): Raw => ({ raw: sql });
const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;
const ts = (iso: string | undefined): Value => {
  if (!iso) return null;
  const seconds = Math.round((anchor.getTime() - Date.parse(iso)) / 1000);
  return raw(`now() - interval '${seconds} seconds'`);
};
const textArray = (values: string[], type: string): Raw =>
  raw(values.length ? `array[${values.map(quote).join(", ")}]::${type}[]` : `'{}'::${type}[]`);

function sqlValue(v: Value): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "object") return v.raw;
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return quote(v);
}

function insert(table: string, rows: Array<Record<string, Value>>): string {
  if (rows.length === 0) return "";
  const columns = Object.keys(rows[0]);
  const values = rows.map((row) => `  (${columns.map((c) => sqlValue(row[c])).join(", ")})`).join(",\n");
  return `insert into ${table} (${columns.join(", ")}) values\n${values};\n\n`;
}

