/**
 * Generates supabase/seed.sql from the TypeScript demo seed so the database and the offline demo
 * share one coherent dataset. Timestamps are written relative to now() so the data always looks current.
 *   npm run db:seed:generate
 */
import { writeFileSync } from "node:fs";
